# Generates the R reference values the statistics engine is checked against
# (packages/core/src/stats/*.test.ts). Base R only; the datasets ship with R.
#
# Usage: Rscript scripts/r/build-stats-reference.R
# Output: packages/core/src/stats/stats-reference.ts (versioned, so the
# tests run in CI without R).

num <- function(x) ifelse(is.finite(x), sprintf("%.17g", x), ifelse(is.na(x), "null", ifelse(x > 0, "Infinity", "-Infinity")))
vec <- function(v) paste0("[", paste(vapply(v, num, ""), collapse = ", "), "]")

dist_rows <- character(0)
add <- function(fn, args, value) {
  dist_rows <<- c(dist_rows, sprintf("  { fn: \"%s\", args: %s, value: %s },", fn, vec(args), num(value)))
}

for (x in c(-38, -8.3, -3, -1.5, -0.2, 0, 0.674, 1.96, 5, 12)) {
  add("pnorm", c(x), pnorm(x)); add("pnormUpper", c(x), pnorm(x, lower.tail = FALSE))
}
for (p in c(1e-300, 1e-20, 1e-6, 0.001, 0.025, 0.3, 0.5, 0.8, 0.975, 0.999999)) add("qnorm", c(p), qnorm(p))
for (df in c(1, 2.5, 7, 30, 250)) {
  for (t in c(-40, -3.2, -1, 0, 0.5, 2.1, 9)) {
    add("pt", c(t, df), pt(t, df)); add("ptUpper", c(t, df), pt(t, df, lower.tail = FALSE))
  }
  for (p in c(1e-12, 0.005, 0.025, 0.5, 0.9, 0.975, 0.999)) add("qt", c(p, df), qt(p, df))
}
for (df in c(1, 2, 3.5, 10, 100)) {
  for (x in c(0.001, 0.5, 1, 3.84, 10, 60, 400)) {
    add("pchisq", c(x, df), pchisq(x, df)); add("pchisqUpper", c(x, df), pchisq(x, df, lower.tail = FALSE))
  }
  for (p in c(1e-10, 0.01, 0.05, 0.5, 0.95, 0.99)) add("qchisq", c(p, df), qchisq(p, df))
}
for (dfs in list(c(1, 1), c(2, 10), c(3, 27), c(5.5, 40), c(20, 200))) {
  for (f in c(0.01, 0.5, 1, 2.5, 4.2, 30, 1000)) {
    add("pf", c(f, dfs), pf(f, dfs[1], dfs[2])); add("pfUpper", c(f, dfs), pf(f, dfs[1], dfs[2], lower.tail = FALSE))
  }
  # The F quantile goes through qbeta and not qf: qf(1e-8, 1, 1) returns 2.22e-16
  # (machine epsilon) and pf of that value is 9.49e-9, not 1e-8. qf computes
  # 1/qbeta(...) - 1 and loses the far tail; df2*x/(df1*(1 - x)) with
  # x = qbeta(p, df1/2, df2/2) matches the closed form tan(pi/2*p)^2 of F(1, 1).
  for (p in c(1e-8, 0.05, 0.5, 0.95, 0.999)) {
    x <- qbeta(p, dfs[1] / 2, dfs[2] / 2)
    add("qf", c(p, dfs), dfs[2] * x / (dfs[1] * (1 - x)))
  }
}

samples <- list(
  iris_sepal_length = iris$Sepal.Length,
  mtcars_mpg = mtcars$mpg,
  toothgrowth_len = ToothGrowth$len,
  small_even = c(4, 1, 3, 3, 10, 2),
  single = c(7)
)
# Sample skewness G1 (Joanes & Gill, 1998, type 2; the one SPSS and Excel report),
# written from its formula: base R has no skewness function.
g1 <- function(x) {
  n <- length(x); if (n < 3) return(NA)
  m2 <- mean((x - mean(x))^2); m3 <- mean((x - mean(x))^3)
  (m3 / m2^1.5) * sqrt(n * (n - 1)) / (n - 2)
}
desc_rows <- character(0)
for (name in names(samples)) {
  x <- samples[[name]]
  q <- quantile(x, c(0, 0.25, 0.5, 0.75, 1), type = 7, names = FALSE)
  desc_rows <- c(desc_rows, paste0(
    "  {\n    name: \"", name, "\",\n    values: ", vec(x), ",\n",
    "    mean: ", num(mean(x)), ", median: ", num(median(x)),
    ", variance: ", num(if (length(x) > 1) var(x) else NA),
    ", sd: ", num(if (length(x) > 1) sd(x) else NA), ",\n",
    "    quartiles: ", vec(q), ", skewness: ", num(g1(x)), ",\n  },"
  ))
}

out <- "packages/core/src/stats/stats-reference.ts"
writeLines(c(
  "// Generated by scripts/r/build-stats-reference.R. Do not edit by hand.",
  paste0("// ", R.version.string, "; base R only."),
  "// biome-ignore-all lint/correctness/noPrecisionLoss: R prints 17 significant digits; the reference is kept exactly as R wrote it.",
  "",
  "export interface DistributionCase {",
  "  readonly fn: string;",
  "  readonly args: readonly number[];",
  "  readonly value: number;",
  "}",
  "",
  "export const DISTRIBUTION_REFERENCE: readonly DistributionCase[] = [", dist_rows, "];",
  "",
  "export interface DescriptiveCase {",
  "  readonly name: string;",
  "  readonly values: readonly number[];",
  "  readonly mean: number;",
  "  readonly median: number;",
  "  readonly variance: number | null;",
  "  readonly sd: number | null;",
  "  readonly quartiles: readonly number[];",
  "  readonly skewness: number | null;",
  "}",
  "",
  "export const DESCRIPTIVE_REFERENCE: readonly DescriptiveCase[] = [", desc_rows, "];"
), out)
cat("wrote", out, length(dist_rows), "distribution cases\n")
