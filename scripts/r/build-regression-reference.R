# Generates the R reference values for linear regression
# (packages/core/src/stats/regression.test.ts): lm() and summary.lm() from
# base R on datasets that ship with R.
# Usage: Rscript scripts/r/build-regression-reference.R
# Output: packages/core/src/stats/regression-reference.ts (versioned).

num <- function(x) sprintf("%.17g", x)
vec <- function(v) paste0("[", paste(vapply(v, num, ""), collapse = ", "), "]")

models <- list(
  mtcars_mpg_wt = list(data = mtcars, y = "mpg", x = c("wt")),
  mtcars_mpg_wt_hp_qsec = list(data = mtcars, y = "mpg", x = c("wt", "hp", "qsec")),
  iris_sepal_petal = list(data = iris, y = "Sepal.Length", x = c("Petal.Length", "Petal.Width")),
  toothgrowth_len_dose = list(data = ToothGrowth, y = "len", x = c("dose"))
)

rows <- character(0)
for (name in names(models)) {
  m <- models[[name]]
  fit <- lm(reformulate(m$x, m$y), data = m$data)
  s <- summary(fit)
  co <- s$coefficients
  f <- s$fstatistic
  rows <- c(rows, paste0(
    "  {\n    name: \"", name, "\",\n",
    "    y: ", vec(m$data[[m$y]]), ",\n",
    "    x: [", paste(vapply(m$x, function(v) vec(m$data[[v]]), ""), collapse = ", "), "],\n",
    "    coefficients: ", vec(co[, 1]), ",\n",
    "    standardErrors: ", vec(co[, 2]), ",\n",
    "    tValues: ", vec(co[, 3]), ",\n",
    "    pValues: ", vec(co[, 4]), ",\n",
    "    sigma: ", num(s$sigma), ", rSquared: ", num(s$r.squared), ", adjustedRSquared: ", num(s$adj.r.squared), ",\n",
    "    f: ", num(f[["value"]]), ", dfModel: ", num(f[["numdf"]]), ", dfResidual: ", num(f[["dendf"]]),
    ", fP: ", num(pf(f[["value"]], f[["numdf"]], f[["dendf"]], lower.tail = FALSE)), ",\n",
    "    residuals: ", vec(unname(residuals(fit))), ",\n  },"
  ))
}

out <- "packages/core/src/stats/regression-reference.ts"
writeLines(c(
  "// Generated by scripts/r/build-regression-reference.R. Do not edit by hand.",
  paste0("// ", R.version.string, "; base R only (lm, summary.lm)."),
  "// biome-ignore-all lint/correctness/noPrecisionLoss: R prints 17 significant digits; the reference is kept exactly as R wrote it.",
  "",
  "export interface RegressionCase {",
  "  readonly name: string;",
  "  readonly y: readonly number[];",
  "  readonly x: readonly (readonly number[])[];",
  "  readonly coefficients: readonly number[];",
  "  readonly standardErrors: readonly number[];",
  "  readonly tValues: readonly number[];",
  "  readonly pValues: readonly number[];",
  "  readonly sigma: number;",
  "  readonly rSquared: number;",
  "  readonly adjustedRSquared: number;",
  "  readonly f: number;",
  "  readonly dfModel: number;",
  "  readonly dfResidual: number;",
  "  readonly fP: number;",
  "  readonly residuals: readonly number[];",
  "}",
  "",
  "export const REGRESSION_REFERENCE: readonly RegressionCase[] = [", rows, "];"
), out)
cat("wrote", out, "\n")
