# Generates the reference values for the effect sizes of the statistics engine
# (packages/core/src/stats/effects.test.ts) with the R package effectsize, an
# implementation independent from this site's formulas.
#
# Needs R and effectsize (it can live in a temporary library):
#   R_LIBS_USER=<dir> Rscript -e 'install.packages("effectsize", lib = "<dir>")'
#   R_LIBS_USER=<dir> Rscript scripts/r/build-effects-reference.R
# Output: packages/core/src/stats/effects-reference.ts (versioned).

suppressMessages(library(effectsize))
num <- function(x) sprintf("%.17g", x)
vec <- function(v) paste0("[", paste(vapply(v, num, ""), collapse = ", "), "]")
mat <- function(m) paste0("[", paste(apply(m, 1, vec), collapse = ", "), "]")

auto <- mtcars$mpg[mtcars$am == 0]; manual <- mtcars$mpg[mtcars$am == 1]
s1 <- sleep$extra[1:10]; s2 <- sleep$extra[11:20]
tab <- unclass(table(mtcars$cyl, mtcars$am))
tab2 <- matrix(c(12, 5, 7, 16), nrow = 2)
groups <- split(iris$Sepal.Length, iris$Species)
fit <- aov(Sepal.Length ~ Species, data = iris)

rows <- c(
  sprintf("  { name: \"cohens_d_pooled\", x: %s, y: %s, value: %s },", vec(auto), vec(manual), num(cohens_d(auto, manual)$Cohens_d)),
  sprintf("  { name: \"hedges_g_pooled\", x: %s, y: %s, value: %s },", vec(auto), vec(manual), num(hedges_g(auto, manual)$Hedges_g)),
  sprintf("  { name: \"cohens_d_paired\", x: %s, y: %s, value: %s },", vec(s1), vec(s2), num(cohens_d(s1, s2, paired = TRUE)$Cohens_d)),
  sprintf("  { name: \"cohens_d_one_sample\", x: %s, mu: 20, value: %s },", vec(mtcars$mpg), num(cohens_d(mtcars$mpg, mu = 20)$Cohens_d)),
  sprintf("  { name: \"cramers_v_adjusted\", table: %s, value: %s },", mat(tab), num(cramers_v(tab)$Cramers_v_adjusted)),
  sprintf("  { name: \"cramers_v_raw\", table: %s, value: %s },", mat(tab), num(cramers_v(tab, adjust = FALSE)$Cramers_v)),
  sprintf("  { name: \"cramers_v_raw_2x2\", table: %s, value: %s },", mat(tab2), num(cramers_v(tab2, adjust = FALSE)$Cramers_v)),
  sprintf("  { name: \"eta_squared\", groups: [%s], value: %s },", paste(vapply(groups, vec, ""), collapse = ", "), num(eta_squared(fit, verbose = FALSE)$Eta2)),
  sprintf("  { name: \"omega_squared\", groups: [%s], value: %s },", paste(vapply(groups, vec, ""), collapse = ", "), num(omega_squared(fit, verbose = FALSE)$Omega2)),
  sprintf("  { name: \"rank_biserial\", x: %s, y: %s, value: %s },", vec(auto), vec(manual), num(rank_biserial(auto, manual)$r_rank_biserial))
)

out <- "packages/core/src/stats/effects-reference.ts"
writeLines(c(
  "// Generated by scripts/r/build-effects-reference.R. Do not edit by hand.",
  paste0("// ", R.version.string, "; effectsize ", as.character(packageVersion("effectsize")), "."),
  "// biome-ignore-all lint/correctness/noPrecisionLoss: R prints 17 significant digits; the reference is kept exactly as R wrote it.",
  "",
  "export interface EffectCase {",
  "  readonly name: string;",
  "  readonly value: number;",
  "  readonly x?: readonly number[];",
  "  readonly y?: readonly number[];",
  "  readonly mu?: number;",
  "  readonly table?: readonly (readonly number[])[];",
  "  readonly groups?: readonly (readonly number[])[];",
  "}",
  "",
  "export const EFFECTS_REFERENCE: readonly EffectCase[] = [", rows, "];"
), out)
cat("wrote", out, "\n")
