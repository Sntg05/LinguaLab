# Generates the R reference values for the keyness measures of the document
# comparison (S13): src/scripts/tools/keyness.test.ts checks the TypeScript
# engine against them.
#
# Base R only, no packages. For each case (a occurrences in a corpus of n1
# words, b occurrences in a corpus of n2 words):
#
# - g2: the deviance of the independence log-linear model fitted with
#   glm(family = poisson) to the 2x2 table (word / other words x corpus 1 / 2).
#   That deviance IS Dunning's (1993) log-likelihood G2, computed by R's own
#   fitting code rather than by re-typing the formula.
# - p: pchisq(g2, df = 1, lower.tail = FALSE).
# - log_ratio: Hardie's (2014) log ratio, log2 of the ratio of relative
#   frequencies. Hardie does not say how to handle a zero frequency; it is
#   replaced by 0.5, the adjustment quanteda's textstat_keyness applies.
#
# Usage: Rscript scripts/r/build-keyness-reference.R

cases <- list(
  c(25, 3, 5000, 8000),
  c(40, 64, 5000, 8000),
  c(10, 0, 1000, 1200),
  c(0, 40, 3000, 3000),
  c(500, 100, 1000000, 1200000),
  c(300, 2, 20000, 20000),
  c(1, 1, 200, 50000),
  c(2000, 20, 30000, 30000)
)

num <- function(x) sprintf("%.17g", x)

rows <- character(0)
for (case in cases) {
  a <- case[1]; b <- case[2]; n1 <- case[3]; n2 <- case[4]
  table <- data.frame(
    count = c(a, n1 - a, b, n2 - b),
    word = factor(c("w", "o", "w", "o")),
    corpus = factor(c("1", "1", "2", "2"))
  )
  g2 <- deviance(glm(count ~ word + corpus, family = poisson, data = table))
  g2 <- max(g2, 0)
  p <- pchisq(g2, df = 1, lower.tail = FALSE)
  log_ratio <- log2((max(a, 0.5) / n1) / (max(b, 0.5) / n2))
  rows <- c(rows, sprintf(
    "  { a: %d, b: %d, n1: %d, n2: %d, g2: %s, p: %s, logRatio: %s },",
    a, b, n1, n2, num(g2), num(p), num(log_ratio)
  ))
}

out <- "src/scripts/tools/keyness-reference.ts"
writeLines(c(
  "// Generated by scripts/r/build-keyness-reference.R. Do not edit by hand.",
  paste0("// ", R.version.string, "; base R only (glm, deviance, pchisq)."),
  "// biome-ignore-all lint/correctness/noPrecisionLoss: R prints 17 significant digits; the reference is kept exactly as R wrote it.",
  "",
  "export interface KeynessReferenceCase {",
  "  readonly a: number;",
  "  readonly b: number;",
  "  readonly n1: number;",
  "  readonly n2: number;",
  "  readonly g2: number;",
  "  readonly p: number;",
  "  readonly logRatio: number;",
  "}",
  "",
  "export const KEYNESS_REFERENCE: readonly KeynessReferenceCase[] = [",
  rows,
  "];"
), out)
cat("wrote", out, "\n")
